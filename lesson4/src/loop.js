// ===== Цикл for: від 0 до 9 =====
console.log('for від 0 до 9:');
for (let i = 0; i <= 9; i++) {
    console.log(i);
}

// ===== Цикл while: від 0 до 9 =====
console.log('\nwhile від 0 до 9:');
let i = 0;
while (i <= 9) {
    console.log(i);
    i++;
}

// ===== Цикл for: від 100 до 0 з кроком 10 =====
console.log('\nfor від 100 до 0 з кроком 10:');
for (let j = 100; j >= 0; j -= 10) {
    console.log(j);
}

// ===== Цикл while: від 100 до 0 з кроком 10 =====
console.log('\nwhile від 100 до 0 з кроком 10:');
let j = 100;
while (j >= 0) {
    console.log(j);
    j -= 10;
}
